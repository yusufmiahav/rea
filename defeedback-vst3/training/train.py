"""Train the feedback-vs-music classifier and export core/model_weights.h.

Data comes from `dfb_sim data` (tools/dfb_sim.cpp): per-track cue vectors from
simulated closed-loop feedback (label 1) and from sung, held, spoken, chordal,
noise and drum sources with and without the loop (label 0). The features are
computed by the same C++ detector that runs in the plugin, so training and
inference see exactly the same numbers.

    python train.py train1.csv [train2.csv ...] --val val.csv --out ../core/model_weights.h
Needs numpy and pandas only.
"""
import argparse
import numpy as np
import pandas as pd

H1, H2 = 16, 8
FEATS = [f"f{i}" for i in range(10)]
NAMES = ["papr", "pnpr", "phpr", "sub", "slope_db_s", "pitch_wobble_cents",
         "level_wobble_db", "age_s", "log2_freq_khz", "level_db"]


def load(paths):
    return pd.concat([pd.read_csv(p) for p in paths], ignore_index=True)


def init(rng, nin):
    def lay(o, i):
        return rng.normal(0, 1 / np.sqrt(i), (o, i)), np.zeros(o)
    w1, b1 = lay(H1, nin); w2, b2 = lay(H2, H1); w3, b3 = lay(1, H2)
    return [w1, b1, w2, b2, w3, b3]


def forward(p, x):
    w1, b1, w2, b2, w3, b3 = p
    h1 = np.tanh(x @ w1.T + b1)
    h2 = np.tanh(h1 @ w2.T + b2)
    o = (h2 @ w3.T + b3)[:, 0]
    return h1, h2, o


def train(x, y, sw, xv, yv, epochs=40, lr=3e-3, batch=4096, seed=0):
    rng = np.random.default_rng(seed)
    p = init(rng, x.shape[1])
    m = [np.zeros_like(a) for a in p]; v = [np.zeros_like(a) for a in p]; t = 0
    best = (1e9, None)
    for ep in range(epochs):
        idx = rng.permutation(len(x))
        for s in range(0, len(x), batch):
            bi = idx[s:s + batch]; xb, yb, wb = x[bi], y[bi], sw[bi]
            h1, h2, o = forward(p, xb)
            pr = 1 / (1 + np.exp(-np.clip(o, -30, 30)))
            g = (pr - yb) * wb / wb.sum()
            w1, b1, w2, b2, w3, b3 = p
            gw3 = g[None, :] @ h2; gb3 = np.array([g.sum()])
            d2 = (g[:, None] @ w3) * (1 - h2 ** 2)
            gw2 = d2.T @ h1; gb2 = d2.sum(0)
            d1 = (d2 @ w2) * (1 - h1 ** 2)
            gw1 = d1.T @ xb; gb1 = d1.sum(0)
            grads = [gw1 + 1e-4 * w1, gb1, gw2 + 1e-4 * w2, gb2, gw3 + 1e-4 * w3, gb3]
            t += 1
            for i, gr in enumerate(grads):
                m[i] = 0.9 * m[i] + 0.1 * gr; v[i] = 0.999 * v[i] + 0.001 * gr ** 2
                p[i] = p[i] - lr * (m[i] / (1 - 0.9 ** t)) / (np.sqrt(v[i] / (1 - 0.999 ** t)) + 1e-8)
        _, _, ov = forward(p, xv)
        pv = 1 / (1 + np.exp(-np.clip(ov, -30, 30)))
        loss = -np.mean(yv * np.log(pv + 1e-7) + (1 - yv) * np.log(1 - pv + 1e-7))
        if loss < best[0]:
            best = (loss, [a.copy() for a in p])
        print(f"epoch {ep + 1:2d} val loss {loss:.4f}")
    return best[1]


def fmt(a):
    return "{" + ", ".join(f"{float(v):.7e}f" for v in np.ravel(a)) + "}"


def export(path, p, mean, scale, info):
    w1, b1, w2, b2, w3, b3 = p
    rows = lambda w: "{" + ", ".join(fmt(r) for r in w) + "}"
    src = f"""// Generated by training/train.py. Do not edit by hand.
// Inputs: {", ".join(NAMES)}
#pragma once
namespace dfb {{ namespace model {{
constexpr int kIn = {w1.shape[1]}, kH1 = {H1}, kH2 = {H2};
constexpr const char* kInfo = "{info}";
inline constexpr float mean[kIn] = {fmt(mean)};
inline constexpr float scale[kIn] = {fmt(scale)};
inline constexpr float w1[kH1][kIn] = {rows(w1)};
inline constexpr float b1[kH1] = {fmt(b1)};
inline constexpr float w2[kH2][kH1] = {rows(w2)};
inline constexpr float b2[kH2] = {fmt(b2)};
inline constexpr float w3[kH2] = {fmt(w3[0])};
inline constexpr float b3 = {float(b3[0]):.7e}f;
}} }}
"""
    open(path, "w").write(src)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("train", nargs="+")
    ap.add_argument("--val", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--epochs", type=int, default=40)
    a = ap.parse_args()
    tr, va = load(a.train), load([a.val])
    x = tr[FEATS].to_numpy(np.float64); y = tr["label"].to_numpy(np.float64)
    xv = va[FEATS].to_numpy(np.float64); yv = va["label"].to_numpy(np.float64)
    mean = x.mean(0); scale = x.std(0) + 1e-6
    x = (x - mean) / scale; xv = (xv - mean) / scale
    # balance classes, and make false cuts on musical material cost more
    sw = np.where(y > 0, 0.5 / y.mean(), 0.5 / (1 - y.mean()))
    sw *= np.where((y == 0) & tr["src"].isin(["held", "sung", "chord"]).to_numpy(), 2.0, 1.0)
    print(f"train rows {len(x)} (pos {int(y.sum())}), val rows {len(xv)} (pos {int(yv.sum())})")
    p = train(x, y, sw, xv, yv, epochs=a.epochs)
    _, _, ov = forward(p, xv); pv = 1 / (1 + np.exp(-ov))
    for thr in (0.42, 0.6, 0.85):
        pred = pv >= thr
        tpr = pred[yv == 1].mean(); fpr = pred[yv == 0].mean()
        print(f"thr {thr:.2f}: catches {tpr * 100:5.1f}% of feedback frames, false {fpr * 100:5.2f}% of music frames")
    for s, g in va.assign(p=pv).groupby("src"):
        neg = g[g.label == 0]
        print(f"  {s:7s} false positives at 0.6: {(neg.p >= 0.6).mean() * 100:5.2f}% of {len(neg)} frames")
    n = len(x)
    export(a.out, p, mean, scale, f"MLP 10-{H1}-{H2}-1 trained on {n // 1000}k simulated frames")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
